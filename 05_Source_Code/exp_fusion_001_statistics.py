"""EXT-FUSION-001 supporting statistical/figure audit (no model training).

Reads ONLY train-partition cross-validated predictions generated by
exp_fusion_001.py. Historical training/validation/test arrays, checkpoints,
and source results are not loaded or modified.

Case-bootstrap intervals and McNemar tests are *exploratory*; they do not
account for model-training uncertainty across alternative CV partitions.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import binomtest
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score, recall_score

ROOT = Path(__file__).resolve().parents[1]
IN_DIR = ROOT / "07_Results" / "exp_fusion_001"
OUT_DIR = ROOT / "07_Results" / "exp_fusion_001_statistics"
LABELS = [0, 1, 2, 3, 4, 5]
NAMES = ["2", "3", "4a", "4b", "4c", "5"]
MODELS = ["majority", "image", "geometry", "fusion"]
PAIRS = [("image", "fusion"), ("geometry", "fusion"),
         ("majority", "fusion"), ("image", "geometry")]
N_BOOT = 5000
SEED = 20261028


def score(y, p):
    return {
        "accuracy": float(accuracy_score(y, p)),
        "balanced_accuracy": float(recall_score(
            y, p, labels=LABELS, average="macro", zero_division=0)),
        "macro_f1": float(f1_score(
            y, p, labels=LABELS, average="macro", zero_division=0)),
    }


def load_audit():
    metrics_path = IN_DIR / "metrics.json"
    pred_path = IN_DIR / "oof_predictions.csv"
    if not metrics_path.is_file() or not pred_path.is_file():
        raise FileNotFoundError("Run EXT-FUSION-001 first")
    audit = json.loads(metrics_path.read_text(encoding="utf-8"))
    if audit.get("experiment") != "EXT-FUSION-001":
        raise ValueError("Wrong experiment ID")
    if audit.get("validation_accessed") is not False or audit.get("test_accessed") is not False:
        raise ValueError("Source must be train-only CV")
    raw = pd.read_csv(pred_path, dtype={"roi_id": str, "case_id": str})
    if len(raw) != 4 * 311 or sorted(raw.model.unique().tolist()) != sorted(MODELS):
        raise ValueError("Expected four models with 311 predictions each")
    for name in MODELS:
        frame = raw[raw.model == name]
        if frame.roi_id.duplicated().any() or len(frame.case_id.unique()) != 203:
            raise ValueError(f"Invalid identifiers for {name}")
    return audit, raw, metrics_path, pred_path


def get_case_predictions(audit, raw):
    cases_ref = None
    truth_ref = None
    aligned = {}
    for name in MODELS:
        frame = raw.loc[raw.model == name].sort_values("roi_id").reset_index(drop=True)
        keys = frame[["roi_id", "case_id", "true_class"]]
        if cases_ref is None:
            cases_ref = keys
        elif not keys.equals(cases_ref):
            raise ValueError("Predictions are not aligned across the models")
        probs = frame[[f"p{x}" for x in NAMES]].to_numpy(dtype=float)
        if not np.isfinite(probs).all() or (probs < -1e-9).any():
            raise ValueError("Invalid probabilities")
        if not np.allclose(probs.sum(axis=1), 1.0, atol=1e-5):
            raise ValueError("Probabilities do not sum to 1")
        if not np.array_equal(probs.argmax(axis=1), frame.predicted_class.to_numpy(dtype=int)):
            raise ValueError("Recorded ROI predictions disagree with probabilities")
        grouped = frame.groupby("case_id", sort=True)
        labels = grouped["true_class"].first().astype(int)
        if not (grouped["true_class"].nunique() == 1).all():
            raise ValueError("Inconsistent labels within a case")
        case_probs = grouped[[f"p{x}" for x in NAMES]].mean()
        if not np.array_equal(case_probs.index.to_numpy(), labels.index.to_numpy()):
            raise ValueError("Case order mismatch")
        if truth_ref is None:
            truth_ref = labels.to_numpy()
        elif not np.array_equal(truth_ref, labels.to_numpy()):
            raise ValueError("Case label mismatch")
        pred = case_probs.to_numpy().argmax(axis=1)
        measured = score(truth_ref, pred)
        documented = audit["models"][name]["pooled_case"]
        for key in measured:
            if not np.isclose(measured[key], documented[key], atol=1e-10):
                raise ValueError(f"Metric mismatch {name} {key}")
        aligned[name] = pred
    if len(truth_ref) != 203 or set(truth_ref) != set(LABELS):
        raise ValueError("Expected 203 cases containing all six classes")
    return truth_ref, aligned


def percentile_ci(values):
    lo, hi = np.percentile(values, [2.5, 97.5])
    return [float(lo), float(hi)]


def exact_mcnemar(truth, left, right):
    lc = left == truth
    rc = right == truth
    left_only = int(np.sum(lc & ~rc))
    right_only = int(np.sum(~lc & rc))
    n = left_only + right_only
    return {
        "left_only_correct": left_only,
        "right_only_correct": right_only,
        "both_correct": int(np.sum(lc & rc)),
        "both_wrong": int(np.sum(~lc & ~rc)),
        "discordant_count": n,
        "exact_mcnemar_two_sided_p": (
            float(binomtest(min(left_only, right_only), n, 0.5).pvalue)
            if n else 1.0
        ),
        "delta_accuracy_right_minus_left": float(np.mean(rc) - np.mean(lc)),
    }


def make_figures(truth, pred, paired):
    plt.rcParams.update({
        "font.family": "DejaVu Sans", "font.size": 10,
        "axes.spines.top": False, "axes.spines.right": False,
        "figure.dpi": 150, "savefig.dpi": 220,
    })
    metric_keys = ["accuracy", "balanced_accuracy", "macro_f1"]
    xs = np.arange(4)
    fig, ax = plt.subplots(figsize=(8.2, 4.4))
    palette = ["0.12", "0.38", "0.62"]
    width = 0.23
    for j, metric in enumerate(metric_keys):
        values = [100 * score(truth, pred[m])[metric] for m in MODELS]
        ax.bar(xs + (j - 1) * width, values, width=width,
               color=palette[j], label=metric.replace("_", " "))
    ax.set_xticks(xs, ["Majority", "Image", "Geometry", "Fusion"])
    ax.set_ylabel("Percentage (%)")
    ax.set_ylim(0, 100)
    ax.set_title("Case-level cross-validated development results")
    ax.legend(frameon=False, ncol=3, fontsize=8)
    fig.tight_layout()
    for fmt in ("png", "svg", "pdf"):
        fig.savefig(OUT_DIR / f"case_cv_metrics.{fmt}", bbox_inches="tight")
    plt.close(fig)

    for name in MODELS:
        cm = confusion_matrix(truth, pred[name], labels=LABELS)
        fig, ax = plt.subplots(figsize=(5.7, 4.9))
        ax.imshow(cm, cmap="Greys")
        max_count = max(cm.max(), 1)
        for i in range(6):
            for j in range(6):
                ax.text(j, i, str(cm[i, j]), ha="center", va="center",
                        color="white" if cm[i, j] > max_count * 0.55 else "black", fontsize=9)
        ax.set_xticks(range(6), NAMES)
        ax.set_yticks(range(6), NAMES)
        ax.set_xlabel("Predicted TI-RADS category")
        ax.set_ylabel("Assigned TI-RADS category")
        ax.set_title(f"{name.title()} | case-level CV confusion matrix")
        fig.tight_layout()
        for fmt in ("png", "svg", "pdf"):
            fig.savefig(OUT_DIR / f"case_confusion_{name}.{fmt}", bbox_inches="tight")
        plt.close(fig)

    fig, ax = plt.subplots(figsize=(8.2, 4.2))
    for i, (left, right) in enumerate(PAIRS):
        entry = paired[f"{left}_to_{right}"]["accuracy"]
        center = 100 * entry["estimate"]
        low, high = [100 * x for x in entry["bootstrap_95_percentile_ci"]]
        ax.errorbar(center, i, xerr=[[center - low], [high - center]],
                    fmt="o", capsize=4, color="0.15", ecolor="0.4")
    ax.axvline(0, color="0.45", linestyle="--", linewidth=1)
    ax.set_yticks(range(len(PAIRS)), [f"{right} - {left}" for left, right in PAIRS])
    ax.invert_yaxis()
    ax.set_xlabel("Difference in case accuracy (percentage points)")
    ax.set_title("Exploratory paired case-bootstrap intervals")
    fig.tight_layout()
    for fmt in ("png", "svg", "pdf"):
        fig.savefig(OUT_DIR / f"paired_accuracy_differences.{fmt}", bbox_inches="tight")
    plt.close(fig)


def main():
    if OUT_DIR.exists():
        raise FileExistsError("Refusing to overwrite prior statistics audit")
    audit, raw, metrics_path, pred_path = load_audit()
    truth, predictions = get_case_predictions(audit, raw)
    rng = np.random.default_rng(SEED)
    indices = rng.integers(0, len(truth), size=(N_BOOT, len(truth)))
    model_stats = {}
    paired = {}
    for name in MODELS:
        base = score(truth, predictions[name])
        accuracy_reps = (predictions[name][indices] == truth[indices]).mean(axis=1)
        model_stats[name] = {
            "case_metrics": base,
            "case_accuracy_bootstrap_95_percentile_ci": percentile_ci(accuracy_reps),
            "case_confusion_matrix": confusion_matrix(
                truth, predictions[name], labels=LABELS).tolist(),
        }
    for left, right in PAIRS:
        diff_reps = (
            (predictions[right][indices] == truth[indices]).mean(axis=1)
            - (predictions[left][indices] == truth[indices]).mean(axis=1)
        )
        pair_key = f"{left}_to_{right}"
        paired[pair_key] = {
            "accuracy": {
                "estimate": float(np.mean(predictions[right] == truth) -
                                  np.mean(predictions[left] == truth)),
                "bootstrap_95_percentile_ci": percentile_ci(diff_reps),
            },
            "paired_correctness": exact_mcnemar(
                truth, predictions[left], predictions[right]),
        }

    OUT_DIR.mkdir(parents=True, exist_ok=False)
    make_figures(truth, predictions, paired)
    outcome = {
        "experiment": "EXT-FUSION-001-STATISTICS",
        "source_experiment": "EXT-FUSION-001",
        "evidence_level": "Exploratory, training-set out-of-fold; not an independent test",
        "case_count": len(truth), "bootstrap_seed": SEED,
        "bootstrap_repetitions": N_BOOT,
        "method": "Case-resampled nonparametric percentile intervals",
        "limitations": [
            "Case bootstrap does not capture training/partition uncertainty of fitted CV models.",
            "Multiple exploratory contrasts are not corrected for multiplicity.",
            "No claim of independent patient identity, pathology labels or clinical utility.",
        ],
        "source_hashes": {
            p.name: hashlib.sha256(p.read_bytes()).hexdigest()
            for p in [metrics_path, pred_path]
        },
        "models": model_stats, "paired_case_comparisons": paired,
    }
    (OUT_DIR / "statistical_audit.json").write_text(
        json.dumps(outcome, indent=2) + "\n", encoding="utf-8")
    with (OUT_DIR / "case_metrics.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(["model", "case_count", "accuracy", "balanced_accuracy",
                         "macro_f1", "accuracy_ci_low", "accuracy_ci_high"])
        for name, record in model_stats.items():
            m = record["case_metrics"]
            lo, hi = record["case_accuracy_bootstrap_95_percentile_ci"]
            writer.writerow([name, len(truth), m["accuracy"], m["balanced_accuracy"],
                             m["macro_f1"], lo, hi])
    print("\nEXT-FUSION-001-STATISTICS COMPLETE")
    for name, record in model_stats.items():
        print(name, "case:", record["case_metrics"])
    for pair, record in paired.items():
        print(pair, "delta and exploratory CI:", record["accuracy"],
              "McNemar p:", record["paired_correctness"]["exact_mcnemar_two_sided_p"])
    print("Saved:", OUT_DIR)
    print("No original files, validation arrays, test arrays, or checkpoints accessed.")


if __name__ == "__main__":
    main()
